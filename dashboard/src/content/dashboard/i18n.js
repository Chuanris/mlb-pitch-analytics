export function translateDashboard(locale, value) {
  if (locale !== "zh-TW" || value === null || value === undefined) return value;
  if (zhTW[value]) return zhTW[value];
  if (typeof value === "string" && value.includes(" · ")) {
    return value.split(" · ").map((part) => zhTW[part] ?? part).join(" · ");
  }
  return value;
}

export function localizeColumns(locale, columns) {
  return columns.map((column) => ({
    ...column,
    label: translateDashboard(locale, column.label),
  }));
}

export function localizeChart(locale, chart) {
  return {
    ...chart,
    ...(chart.xLabel ? { xLabel: translateDashboard(locale, chart.xLabel) } : {}),
    ...(chart.yLabel ? { yLabel: translateDashboard(locale, chart.yLabel) } : {}),
  };
}
